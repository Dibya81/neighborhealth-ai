const DICTS: Record<Lang, Partial<Dict>> = { en, kn, hi };
export type TKey = keyof Dict;

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>) {
  let s = DICTS[lang]?.[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function bandLabel(lang: Lang, band: Band) {
  return translate(lang, `band.${band}` as TKey);
}

